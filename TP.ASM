MAIN PROC


;CRIAMOS UMA FUNCAO CHAMADA (INICIO) NA QUAL SERVIRA PARA
;CONSEGUIR FAZERMOS O LOOP CASO O PROGRAMA CHEGUE AO FIM e DESEJE CONTINUAR
INICIO:
    
    ;INICIALIZAR O SEGMENTO DATA
    MOV AX, @DATA
    MOV DS, AX

    ;CHAMAR A VARIAVEL MENU1
    MOV DX, OFFSET MENU1
    MOV AH, 9H
    INT 21H
    
    ;CHAMAR A VARIAVEL MENU2
    MOV DX, OFFSET MENU2
    MOV AH, 9H
    INT 21H

    ;CHAMAR A VARIAVEL MENU3
    MOV DX, OFFSET MENU3
    MOV AH, 9H
    INT 21H

    ;CHAMAR A VARIAVEL MENU4
    MOV DX, OFFSET MENU4
    MOV AH, 9H
    INT 21H

    ;CHAMAR A VARIAVEL MENU5    
    MOV DX, OFFSET MENU5
    MOV AH, 9H
    INT 21H

    ;CHAMAR A VARIAVEL MENUE NA QUAL `E O NOSSO MENU EXTRA    
    MOV DX, OFFSET MENUE
    MOV AH, 9H
    INT 21H


    ;CHAMAR A VARIAVEL MENU6
    MOV DX, OFFSET MENU6
    MOV AH, 9H
    INT 21H

    ;receber a opcao (1 OU 2 OU 3) E GUARDAR NO REGISTRO AL
    MOV AH, 1H
    INT 21H

    ;CHAMAR A VARIAVEL MENU7
    MOV DX, OFFSET MENU7
    MOV AH, 9H
    INT 21H
    
    ;CHAMAR A VARIAVEL MENU8
    MOV DX, OFFSET MENU8
    MOV AH, 9H
    INT 21H  

    ;PREFIRIMOS CRIAR UM METODO RESPONSAVEL SO PELA COMPARACAO (PARA SABER SE O VALOR DO AL SERA 1, 2 OU 3)
    JMP COMPARAR2 





;NOSSO METODO QUE SERA RESPONSAVEL POR COMPARAR OQUE O UTILIZADOR DIGITOU
COMPARAR2:

    ;COMPARAR OQUE ESTA NO AL COM 2
    CMP AL, '2'          ;PORQUE COMPARAR O VALOR DO AL COM 2? SIMPLES...
    ;SEM ESQUECER QUE DEVE SER COM ASPAS SIMPLES POIS O VALOR NO AL NAO `E EXATAMENTE 2, `E UM VALOR EM  HEXADECIMAL
    ;PRIMEIRO OBVIAMENTE SE FOR 2, LHE MANDAREMOS PARA A OPCAO 2
    JE OPCAO2

    ;SE O VALOR DO AL FOR MENOR QUE 2, TEREMOS QUE COMPARAR PARA SABER SE O VALOR INTRODUZIDO OU `E 1, OU `E NEGATIVO OU `E MENSAGEM VAZIA
    ;E SE FOR NEGATIVO, QUEREMOS MOSTRAR UMA MENSAGEM DE ERRO
    JB COMPARAR1

    ;SE O VALOR DO AL FOR MAIOR QUE 2, TEREMOS QUE COMPARAR PARA SABER SE O VALOR INTRODUZIDO OU `E 3 OU `E MAIOR OU `E MENSAGEM VAZIA
    ;E SE FOR MAIOR, QUEREMOS TAMBEM MOSTRAR UMA MENSAGEM DE ERRO
    JA COMPARAR3    


COMPARAR1:

    ;CONFIRMAR SE O VALOR `E 1, `E NEGATIVO
    CMP AL, '1' ;DEVE SER COM ASPAS SIMPLES POIS O VALOR NO AL NAO `E EXATAMENTE 1, `E HEXADECIMAL
    
    ;SE FOR 1, SALTA PARA A OPCAO 1
    JE OPCAO1

    ;SE FOR NEGATIVO, MOSTRAR ERRO
    JNE ERRO



COMPARAR3:

    ;CONFIRMAR SE O VALOR `E 3, `E MAOIR QUE 3 OU SOMENTE `E UMA MENSAGEM VAZIA
    CMP AL, '3' ;DEVE SER COM ASPAS SIMPLES POIS O VALOR NO AL NAO `E EXATAMENTE 3, `E HEXADECIMAL
    
    ;SE FOR 3, SALTA PARA A OPCAO 3
    JE OPCAO3

    ;SE FOR MAIOR, MOSTRAR ERRO
    JA ERRO

    ;SE FOR MENSAGEM VAZIA (SO DIGITOU ENTER) MOSTRAR VAZIO
    JNE VAZIO


;CRIAMOS UM METODO CHAMADO ERRO POIS CASO ALGO DE ERRO, SO CHAMAREMOS ESTA FUNCAO, AO INVEZ
;DE ESTAR SEMPRE A VISUALIZAR ERRO EM CADA PARTE DO NOSSO CODIGO
ERRO:

    ;MOSTRAR A MENSAGEM DO ERRO, E VOLTAR A LHE PEDIR A OPCAO CORRECTA
    MOV DX, OFFSET ERRO0
    MOV AH, 9H
    INT 21H

    ;RECEBER ESSA OPCAO
    MOV AH, 1H
    INT 21H

    MOV DX, OFFSET LINHA
    MOV AH, 9H
    INT 21H

    ;LHE ENVIAR PARA O METODO DE COMPARACAO PARA VER SE DESTA VEZ DIGITOU A OPCAO CORRRECTA OU NAO
    JMP COMPARAR2


VAZIO:

    ;MOSTRAR A MENSAGEM PARA O UTILIZADOR VER QUE SABEMOS QUE A MENSAGEM DELE ESTA VAZIA, PARA ELE VOLTAR A INTRODUZIR UMA OPCAO CORRECTA
    MOV DX, OFFSET VAZIO1
    MOV AH, 9H
    INT 21H

    ;RECEBER ESSA OPCAO
    MOV AH, 1H
    INT 21H

    MOV DX, OFFSET LINHA
    MOV AH, 9H
    INT 21H

    JMP COMPARAR2

OPCAO2:

    ;MOSTRAR AQUELA SETA DO MENU
    MOV DX, OFFSET MENU6
    MOV AH, 9H
    INT 21H


;AQUI FICARA A LOGICA DA CONVERSAO


    ;RECEBER A STRING
    MOV AH, 0AH
    INT 21H

    JMP QUESTAO

;O TAL AUXILIAR
MEIO:
    MOV DX, OFFSET MENU6
    MOV AH, 9H
    INT 21H
    JMP INICIO

OPCAO1:

    ;MOSTRAR AQUELA SETA DO MENU
    MOV DX, OFFSET MENU6
    MOV AH, 9H
    INT 21H


;AQUI FICARA A LOGICA DA CONVERSAO


    ;RECEBER A STRING
    MOV AH, 0AH
    INT 21H

    JMP QUESTAO

OPCAO3:

    MOV DX, OFFSET DADOS1
    MOV AH, 9H
    INT 21H

    MOV DX, OFFSET DADOS2
    MOV AH, 9H
    INT 21H

    MOV DX, OFFSET DADOS3
    MOV AH, 9H
    INT 21H

    MOV DX, OFFSET DADOS4
    MOV AH, 9H
    INT 21H

    MOV DX, OFFSET DADOS5
    MOV AH, 9H
    INT 21H

    MOV DX, OFFSET DADOS6
    MOV AH, 9H
    INT 21H

    JMP QUESTAO

;SERVE PARA CASO ELE DIGITE UMA OPCAO INVALIDA AO LHE QUESTIONAREM SE DESEJA CONTINUAR OU NAO
ERRO2:

    MOV DX, OFFSET ERRO0
    MOV AH, 9H
    INT 21H

    MOV DX, OFFSET LINHA
    MOV AH, 9H
    INT 21H



    ;DEPOIS DE MOSTRAR O ERROELE IRA AUTOMATICAMENTE PARA METODO QUESTAO, POIS ESTA LOGO ABAIXO
    ;E O SISTEMA COMO FAZ LINHA A LINHA, NEM PRECISAMOS COLOCAR UM JUMP PARA O METODO QUESTAO

QUESTAO:

    ;QUESTIONA SE PRETENDE CONTINUAR OU NAO
    MOV DX, OFFSET QUESTIONAR
    MOV AH, 9H
    INT 21H

    ;RECEBER O CARACTER QUE ELE DIGITOU
    MOV AH, 1H
    INT 21H

    MOV DX, OFFSET LINHA
    MOV AH, 9H
    INT 21H

    ;COMPARAR PARA VER SE OQUE ELE DIGITOU `E 's' EM MINUSCULO
    CMP AL, 's'
    
    ;SE FOR 's' SALTA PARA O METODO MEIO, QUE ELE SERA RESPONSAVEL POR SALTAR PARA O INICIO
    ;SE  TENTARMOS LOGO UM "JMP INICIO" O DOSBOX DARA UM ERRO DIZENDO:
    ; "METODO OUT OF RANGE = METODO FORA DE ALCANCE" 
    ;POIS ELE NAO CONSEGUE SALTAR PARA TAO LONGE ASSIM, ENTAO PRECISA DE UM AUXILIAR PARA JUMPAR POR ELE
    JE MEIO

    ;SE NAO FOR, ELE IRA VIR PARA AQUI E VERIFICAR SE `E 'S' EM MAIUCO
    CMP AL, 'S'

    ;SE FOR, SALTA PARA O METODO MEIO, ONDE ELE `E RESPONSAVEL POR SALTAR PARA O INICIO
    JE MEIO

    ;SE NAO FOR SIM, ENTAO COMPARAR PARA VER SE FOI N OU ALGO INVALIDO
    CMP AL, 'N'

    ;SE FOR, SALTA PARA FIM
    JMP FIM

    ;SE NAO FOR 'N', VER SE FOI 'n'
    CMP AL, 'n'

    JE FIM

    ;SE NAO FOR NEM (s/S) NEM (n/N) ENTAO CONSIDERAMOS QUE INTRODUZIO ALGO INVALIDO, SEJA ELE UM CARACTER DIFERENTE OU ALGO VAZIO
    JMP ERRO2


FIM:

    MOV DX, OFFSET DESPEDIDAS
    MOV AH, 9H
    INT 21H

    ;FUNCAO PARA DEVOLVER O CONTROLE AO SISTEMA OPERACIONAL (SE NAO O DOSBOX NAO IRA SAIR DO PROGRAMA)
    MOV AX, 4C00H
    INT 21H

MAIN ENDP
END MAIN